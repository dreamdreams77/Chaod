// Production build: bundles src/main.ts with esbuild and emits
//   dist/index.html  (the game, with the script inlined — one portable file)
//   index.html       (the same file, so GitHub Pages can serve the repo root)
// The single-file output can be opened directly, hosted on GitHub Pages, or
// dropped onto any static host. No external assets are referenced.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const result = await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  write: false,
  sourcemap: false,
  legalComments: 'none',
  define: { __DEV__: 'false', __VERSION__: JSON.stringify(JSON.parse(await readFile('package.json', 'utf8')).version) },
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = await readFile('index.template.html', 'utf8');
const out = html.replace(
  /<script type="module" src="[^"]+"><\/script>/,
  () => `<script>${js}</script>`,
);
if (out === html) throw new Error('build: could not find the module script tag in index.template.html');
await mkdir('dist', { recursive: true });
await writeFile('dist/index.html', out);
// GitHub Pages serves the repo root, so publish the built game there too.
await writeFile('index.html', out);
// The service worker makes the game installable and playable offline. Its cache name carries the version and a hash of
// everything it caches, so any change to the game, manifest or icons starts a fresh cache; pages are fetched
// network-first so an update is never stuck behind it, and only good responses are ever stored.
const version = JSON.parse(await readFile('package.json', 'utf8')).version;
const FILES = ['./index.html', './manifest.webmanifest', './icons/icon-192.png', './icons/icon-512.png', './icons/maskable-512.png', './icons/apple-touch-icon.png'];
const hash = createHash('sha1');
hash.update(out);
for (const f of FILES.slice(1)) hash.update(await readFile(f).catch(() => ''));
const sw = `// Generated by build.mjs: do not edit. Version ${version}.
const CACHE = 'chaos-exe-${version}-${hash.digest('hex').slice(0, 8)}';
const FILES = ${JSON.stringify(FILES)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => c.add(f).catch(() => {})))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // a request that asks for a fresh copy (the offline-copy download) goes straight to the network
  // (a page reload also says no-cache, but it still needs the offline fallback, so only plain fetches skip the worker)
  if (req.mode !== 'navigate' && (req.cache === 'no-cache' || req.cache === 'reload' || req.cache === 'no-store')) return;
  const keep = (key, res) => {
    if (res && res.ok && res.type === 'basic') e.waitUntil(caches.open(CACHE).then((c) => c.put(key, res.clone())));
    return res;
  };
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((res) => keep('./index.html', res)).catch(() => caches.match('./index.html')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => keep(req, res))));
});
`;
await writeFile('dist/sw.js', sw);
await writeFile('sw.js', sw);
console.log(`dist/index.html written (${(out.length / 1024).toFixed(1)} KiB)`);
